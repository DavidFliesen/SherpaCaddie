"""Regenerate the Phase 1 clip and cues with Flite 2.2 (SLT) and FFmpeg."""
import ctypes as c
import ctypes.util
import json
from pathlib import Path
import subprocess
from tempfile import TemporaryDirectory
import wave

ANSWER = "Pick one safe target. Take a smooth practice swing, then step in and commit."
PHONES = {
    "closed": "pau p b m",
    "bite": "f v",
    "teeth": "s z sh zh ch jh th dh",
    "wide": "iy ih ey eh y",
    "round": "w uw uh ow oy ao",
    "open": "aa ae ah aw ay",
    "small": "t d k g n ng l r er hh ax",
}
DIRECTORY = Path(__file__).resolve().parent


def library(name):
    path = ctypes.util.find_library(name)
    if not path:
        raise RuntimeError(f"Install the {name} shared library.")
    return c.CDLL(path)


def bind(lib, name, result, *arguments):
    function = getattr(lib, name)
    function.restype = result
    function.argtypes = arguments
    return function


def generate(wav_path):
    flite = library("flite")
    voice = library("flite_cmu_us_slt")
    pointer, string = c.c_void_p, c.c_char_p
    bind(flite, "flite_init", c.c_int)()
    speaker = bind(voice, "register_cmu_us_slt", pointer, string)(None)
    utterance = bind(flite, "flite_synth_text", pointer, string, pointer)(ANSWER.encode(), speaker)
    if not utterance:
        raise RuntimeError("Flite did not synthesize the demo.")
    try:
        audio = bind(flite, "utt_wave", pointer, pointer)(utterance)
        save = bind(flite, "cst_wave_save_riff", c.c_int, pointer, string)
        if save(audio, str(wav_path).encode()) != 0:
            raise RuntimeError("Flite could not save the demo.")
        segments = bind(flite, "utt_relation", pointer, pointer, string)(utterance, b"Segment")
        item = bind(flite, "relation_head", pointer, pointer)(segments)
        next_item = bind(flite, "item_next", pointer, pointer)
        phone_of = bind(flite, "item_feat_string", string, pointer, string)
        end_of = bind(flite, "item_feat_float", c.c_float, pointer, string)
        lookup = {phone: pose for pose, phones in PHONES.items() for phone in phones.split()}
        cues = []
        start = 0
        while item:
            phone = phone_of(item, b"name").decode()
            end = round(end_of(item, b"end") * 1000)
            if end > start:
                pose = lookup[phone]
                if cues and cues[-1]["viseme"] == pose:
                    cues[-1]["endMs"] = end
                else:
                    cues.append({"startMs": start, "endMs": end, "viseme": pose})
                start = end
            item = next_item(item)
    finally:
        bind(flite, "delete_utterance", None, pointer)(utterance)
        bind(voice, "unregister_cmu_us_slt", None, pointer)(speaker)

    with wave.open(str(wav_path)) as audio_file:
        duration = round(audio_file.getnframes() / audio_file.getframerate() * 1000)
    if abs(duration - start) > 60 or len(cues) < 10:
        raise RuntimeError("Unexpected Flite segment timings.")
    return {"text": ANSWER, "durationMs": duration, "visemes": cues}


def main():
    output = DIRECTORY.parent / "assets" / "sage-local" / "practice.mp3"
    output.parent.mkdir(parents=True, exist_ok=True)
    with TemporaryDirectory() as scratch:
        wav_path = Path(scratch) / "demo.wav"
        demo = generate(wav_path)
        subprocess.run(["ffmpeg", "-loglevel", "error", "-y", "-i", str(wav_path),
                        "-codec:a", "libmp3lame", "-b:a", "40k", str(output)], check=True)
    data = json.dumps(demo, indent=2)
    (DIRECTORY / "demo.mjs").write_text(
        "// Generated by generate-demo.py from Flite's Segment relation.\n"
        f"export const DEMO = {data};\n", encoding="utf-8")


if __name__ == "__main__":
    main()
